// Что в расчёте проекта подтверждено источниками, а что принято по умолчанию или оценено. Без DOM.
// Подтверждено (не менее двух независимых источников): чашка петли Ø35×13, отступ планки 37 мм и шаг 32 мм, диапазон K 3–6 мм;
// ширина короба на шариковых направляющих (проём − 26 мм) и их ряд длин 250–600 мм; ширина короба на скрытых направляющих
// (Blum MOVENTO и Hettich Quadro: проём − 42 мм, Blum TANDEM для плиты 19 мм: проём − 49 мм); сетка 32 мм.
// Остальное перечисляется функцией unverifiedList и помечается в интерфейсе и задании как «не подтверждено источниками».

const has = (P, fn) => (P.sections || []).some(fn);
const drawers = P => has(P, s => (s.items || []).some(i => i.type === 'drawer' || i.type === 'idrawer'));
const doorsOf = P => (P.sections || []).map(s => s.door).filter(d => d && d !== 'none');

/** Список непроверенных допущений проекта: [{ id, what }]. P — один корпус. */
export function unverifiedList(P) {
  const out = [], add = (id, what) => out.push({ id, what });
  if (drawers(P)) {
    add('slide.holes', 'Положение отверстий под направляющие ящиков (первое и последнее от края по 37 мм, высота) принято по общей практике: в источниках не подтверждено.');
    add('slide.load', 'Допустимая нагрузка на направляющие у производителей расходится (20–45 кг), в проверке принята ориентировочно.');
    if (P.slide === 'ballSoft') add('slide.soft', 'Шариковые с доводчиком: геометрия принята как у обычных шариковых, данных по доводчикам не найдено.');
    if (P.slide === 'roller') add('slide.roller', 'Роликовые направляющие: зазор 25 мм, ход 75 % и длины 250–500 мм не подтверждены источниками.');
    if (['hidden', 'tandem', 'quadro'].includes(P.slide)) add('slide.lens', 'Ряд длин скрытых направляющих (270–600 мм) и схема их присадки не подтверждены: сверьте с каталогом производителя.');
  }
  const doors = doorsOf(P), hinged = P.doorType !== 'sliding' ? doors.filter(d => d !== 'flapUp' && d !== 'flapDown') : [];
  if (P.doorType !== 'sliding' && doors.length) {
    add('hinge.count', 'Число петель по высоте двери (2 до 900 мм, 3 до 1600, 4 до 2100, 5 выше) — общая практика: источники расходятся и по порогам, и по массе двери.');
    add('hinge.offset', 'Отступ первой петли от края двери 100 мм найден только в одном источнике.');
    add('hinge.load', 'Нагрузка на петлю (7 кг) не подтверждена производителями.');
  }
  if (hinged.length && (P.sections || []).length > 1) add('hinge.half', 'Полунакладные петли на общей перегородке: данных не найдено, приняты параметры накладной петли.');
  if (doors.some(d => d === 'flapUp' || d === 'flapDown')) add('hinge.flap', 'Петли откидных фасадов: параметры приняты как у накладной петли, данных не найдено.');
  if (doors.includes('flapUp')) add('lift.calc', 'Подбор газлифта по массе фасада — собственная оценка (плечо 0,45 высоты, запас 15 %), не данные производителя: сверьте усилие с каталогом.');
  if (P.doorType === 'sliding') add('kupe', 'Двери-купе: перехлёст 25 мм и вычеты по высоте приняты по одной системе (Aristo); для вашей системы (Boyard, Raumplus и др.) формулы могут отличаться.');
  if (has(P, s => (s.acc || []).length)) add('acc', 'Пределы размеров аксессуаров (пантограф, выдвижная штанга, брючница, обувница) — ориентиры, не данные производителя.');
  if (has(P, s => (s.items || []).some(i => i.type === 'rod'))) add('rod', 'Прогиб штанги считается для трубы Ø25 со стенкой 1 мм и нагрузкой из параметров: это допущения, а не данные вашей штанги.');
  if (doors.length) add('warp', 'Предел коробления фасадов (высота/толщина 150 для ЛДСП, 190 для МДФ) — оценка, нормативного значения не найдено.');
  return out;
}

/** Все допущения проекта с модулями: [{ id, what, modules: [названия] }] без повторов. */
export function unverifiedProject(root, names = []) {
  const seen = new Map(), list = [root, ...((root.modules || []).map(m => m.P))];
  list.forEach((P, i) => { for (const u of unverifiedList(P)) { const e = seen.get(u.id) || seen.set(u.id, { ...u, modules: [] }).get(u.id); if (names[i]) e.modules.push(names[i]); } });
  return [...seen.values()];
}
