// Инструкция по сборке: этапы из spec (поле asm у деталей, hwx у фурнитуры) с номерами деталей из спецификации. Без DOM.
import { STAGES } from './model.js';
import { partKey } from './export.js';

const nz = v => String(Math.round(v * 10) / 10).replace('.', ',');
const TOOL = { confirmat: 'шестигранный ключ 4 мм или бита для конфирматов', minifix: 'отвёртка Pozidriv PZ2', dowel: 'киянка, клей ПВА', screw: 'шуруповёрт, бита PZ2', hinge: 'отвёртка PZ2, шаблон для разметки планок', slide: 'шуруповёрт, угольник', shelfPin: '', rod: 'ножовка по металлу (если штанга длиннее)', bracket: 'шуруповёрт', leg: 'ключ для регулировки опор', pushLatch: 'шуруповёрт', handle: 'шуруповёрт, шаблон межосевого', wallFix: 'дрель, уровень, бур по стене', wallDowel: 'дрель, уровень' };
const BASE_TOOLS = ['рулетка', 'уровень'];

/** Название и порядок этапов для показа. */
export const STAGE_TITLES = { base: 'Основание', carcass: 'Боковины и дно', dividers: 'Перегородки', fixed: 'Стационарные полки', back: 'Задняя стенка в паз', top: 'Крышка', backOverlay: 'Задняя стенка накладная', cornice: 'Карниз', shelves: 'Съёмные полки', rods: 'Штанги', drawerBox: 'Короба ящиков', drawers: 'Установка ящиков', doors: 'Двери', flaps: 'Откидные фасады', handles: 'Ручки', kupe: 'Двери-купе', final: 'Крепление к стене' };

/**
 * Шаги сборки: [{ no, stage, title, text: [строки], parts: [{no, name, qty, L, W, T}], hw: [{name, qty}], tools: [строки], partRefs: [деталь spec] }].
 * groups — результат groupParts (номера деталей совпадают со спецификацией).
 */
export function assemblySteps(spec, groups, P) {
  const noOf = new Map(groups.map(g => [partKey(g), g.no])), info = new Map(groups.map(g => [g.no, g]));
  const part = p => noOf.get(partKey(p));
  const steps = [];
  for (const st of STAGES) {
    const ps = spec.parts.filter(p => p.asm === st), hw = (spec.hwx || []).filter(e => e.stage === st);
    if (!ps.length && !hw.length) continue;
    const byNo = new Map();
    for (const p of ps) { const n = part(p); byNo.set(n, (byNo.get(n) || 0) + 1); }
    const list = [...byNo].map(([no, qty]) => { const g = info.get(no); return { no, name: g.name, qty, L: g.L, W: g.W, T: g.T }; });
    const nums = names => { const l = list.filter(x => names.test(x.name)); return l.map(x => `№${x.no}${x.qty > 1 ? ` (${x.qty} шт.)` : ''}`).join(', '); };
    const of = re => ps.filter(p => re.test(p.name));
    const text = [], tools = new Set(BASE_TOOLS);
    const joint = P.joint || 'confirmat';
    const jointText = () => (joint === 'confirmat' ? 'Закрутите конфирматы 7×50 через пласть в торец. Точки — в 50 мм от краёв.' : joint === 'minifix' ? 'Вкрутите штифты в пласть, вставьте шканты, соберите узел и затяните эксцентрики отвёрткой. Эксцентрики смотрят в сторону торца.' : 'Смажьте шканты клеем, вставьте в торцы и сведите детали, стяните струбцинами до высыхания клея.');
    const tops = ps.filter(p => p.plane === 'xz').map(p => Math.round(p.c[1] + p.T / 2));
    switch (st) {
      case 'base':
        if (P.base === 'legs') text.push(`Вверните регулируемые опоры (высота ${nz(P.plinth)} мм) в нижние точки изделия: по краям, на расстоянии 50 мм от кромок. Пока они в упаковке, сборку лучше вести на мягкой подложке.`);
        else text.push(`Соберите раму цоколя из деталей ${nums(/Цоколь/)}. Рама стоит на полу, передняя доска отступает от фасада на 50 мм. Детали скрепите мебельными уголками.`);
        break;
      case 'carcass': {
        const lone = P.base === 'plinth' ? ' Боковины ставьте на раму цоколя.' : '';
        text.push(`Положите левую боковину ${nums(/Боковина левая/)} пластью вниз и закрепите дно ${nums(/^Дно$/)} вровень с нижним краем, затем поставьте правую боковину ${nums(/Боковина правая/)}.${lone}`, jointText());
        text.push('Проверьте прямоугольность по диагоналям: разница не более 2 мм.');
        break;
      }
      case 'dividers':
        text.push(`Установите перегородки ${nums(/Перегородка/)} между дном и местом крышки, по положениям на схеме (отступ спереди одинаковый).`, jointText());
        if (nums(/Цоколь средний/)) text.push(`Когда перегородки стянуты, подведите под каждую среднюю опору цоколя ${nums(/Цоколь средний/)} и закрепите уголками к дну: конфирматы перегородок идут через дно снизу, до этого их головки закрыты.`);
        break;
      case 'fixed':
        text.push(`Установите ${nums(/Полка (стационарная|антресоли|зоны)|Полуперегородка/)}. Высоты верха полок от пола, мм: ${[...new Set(of(/Полка (стационарная|антресоли|зоны)/).map(p => Math.round(p.c[1] + p.T / 2)))].sort((a, b) => a - b).join(', ') || '—'}.`, jointText());
        break;
      case 'back':
        text.push(`Вставьте заднюю стенку ${nums(/Задняя стенка/)} (ХДФ) в пазы боковин и дна. Пока крышки нет, стенка заходит сверху.`, 'Выровняйте по диагоналям, стенка должна лежать в пазу без перекоса.');
        break;
      case 'top':
        text.push(`Установите крышку ${nums(/Крышка/)}${P.topType === 'overlay' ? ` накладной (свес ${nz(P.topOverhang)} мм)` : ' между боковин'}.`, jointText());
        if (P.backType === 'groove') text.push('Крышка садится на заднюю стенку, которая уже стоит в пазах.');
        break;
      case 'backOverlay':
        text.push(`Приложите заднюю стенку ${nums(/Задняя стенка/)} (ХДФ) с тыльной стороны, выровняйте по диагоналям и закрепите саморезами 3,5×16 с шагом 150 мм (в боковины, дно, крышку, перегородки).`);
        break;
      case 'cornice':
        text.push(`Положите карниз ${nums(/Карниз/)} на крышку и закрепите снизу саморезами 4×30.`);
        break;
      case 'shelves':
        text.push(`Вставьте полкодержатели в отверстия под нужную высоту (по четыре под каждую полку) и положите полки ${nums(/Полка (съёмная|стеклянная)/)}. Верх полок от пола, мм: ${[...new Set(tops.length ? of(/Полка (съёмная|стеклянная)/).map(p => Math.round(p.c[1] + p.T / 2)) : [])].sort((a, b) => a - b).join(', ')}.`);
        break;
      case 'rods':
        text.push('Закрепите штангодержатели на боковинах двумя саморезами каждый и положите штангу в держатели. Высоты штанг от пола, мм: ' + [...new Set(spec.extras.filter(e => e.name === 'Штанга').map(e => Math.round(e.c[1])))].sort((a, b) => a - b).join(', ') + '.');
        break;
      case 'drawerBox':
        text.push(`Соберите короба ящиков из деталей ${nums(/ящика/)} на конфирматах 7×50: передняя и задняя стенки между боковинами, дно ХДФ прибейте или прикрутите снизу.`, 'Проверьте диагонали короба: они должны совпадать.');
        break;
      case 'drawers':
        text.push(`Закрепите ${P.slide === 'hidden' ? 'скрытые' : P.slide === 'roller' ? 'роликовые' : 'шариковые'} направляющие в отверстиях Ø5 на боковинах${of(/Проставка/).length ? ' (сначала проставки к боковинам)' : ''}, затем навесьте короба и закрепите фасады ${nums(/Фасад ящика/)} четырьмя саморезами 4×25 изнутри. Зазор между фасадами 3–4 мм.`);
        break;
      case 'doors':
        text.push(`Вставьте планки петель в отверстия Ø5 на опорах, прижмите чашки в отверстия Ø35 на дверях и навесьте двери ${nums(/Фасад двери|Стекло фасада|Зеркало/)}. Регулировочными винтами выставьте зазоры 2–3 мм.`);
        if (P.hinge === 'wide') text.push('Петли 165° открываются почти до корпуса: не прислоняйте дверь к соседней.');
        break;
      case 'flaps':
        text.push(`Навесьте откидной фасад ${nums(/Фасад откидной/)} на петли, закрепите газлифты или стабилизаторы с обеих сторон корпуса на одинаковой высоте. Ответные планки ставятся по месту.`);
        break;
      case 'handles':
        text.push(P.push ? 'Закрепите толкатели push-to-open на опорах и ответные пластины на дверях. Ручек нет.' : 'Прикрутите ручки в отверстия, подготовленные на фасадах (на ящиках за дверью ручек нет, захват выбран под пальцы).');
        break;
      case 'kupe':
        text.push(`Закрепите верхний рельс к крышке и нижний к дну, соберите полотна из профилей и вставок ${nums(/Вставка двери-купе/)}, навесьте на ролики: сначала заднее, затем переднее полотно. Отрегулируйте высоту роликов.`);
        break;
      case 'final':
        text.push('Закрепите анкерные уголки сзади под крышкой, придвиньте изделие к стене, выставьте по уровню и прикрутите к стене дюбелями. Тип дюбеля подберите по материалу стены.');
        break;
    }
    for (const e of hw) if (TOOL[e.kind]) tools.add(TOOL[e.kind]);
    steps.push({ stage: st, title: STAGE_TITLES[st], text, parts: list, hw: hw.map(e => ({ name: e.name, qty: e.qty })), tools: [...tools], partRefs: ps });
  }
  steps.forEach((s, i) => { s.no = i + 1; });
  return steps;
}
